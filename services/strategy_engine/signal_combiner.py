"""
AI Quant Trading Platform — Signal Combiner & Ensemble Scorer.

Unifies signals generated by multiple strategies or models for a given symbol.
Handles:
1. Conflict Resolution: Conflicting BUY and SELL signals result in HOLD (NO TRADE).
2. Weighted Ensemble Scoring: Strategies are weighted based on confidence and configuration.
3. Consensus Assessment: Ensures sufficient alignment before committing capital.
4. Stop/Target Synthesis: Selects conservative risk-managed execution parameters.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any

from core.logging import get_logger
from strategies.base import SignalDirection, StrategySignal

logger = get_logger("signal_combiner")


@dataclass(slots=True)
class CombinedSignal:
    """Consolidated signal ready for the Risk and Portfolio engines."""
    symbol: str
    direction: SignalDirection
    composite_score: float             # 0.0 to 1.0
    confidence: float                  # Weighted confidence
    consensus_ratio: float             # E.g. 1.0 if all agree, 0.67 if 2 of 3 agree
    contributing_strategies: list[str]
    suggested_stop: float | None = None
    suggested_target: float | None = None
    expected_return: float | None = None
    risk_estimate: float | None = None
    is_approved: bool = False
    reasons: list[str] = field(default_factory=list)
    signals: list[StrategySignal] = field(default_factory=list)
    timestamp: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
    ttl_seconds: float = 14400.0       # 4-hour default validity for signal
    revalidation_required: bool = False
    status: str = "PENDING"            # PENDING, APPROVED, REVALIDATED, EXPIRED, INVALIDATED

    @property
    def is_expired(self) -> bool:
        now = datetime.now(timezone.utc)
        return (now - self.timestamp).total_seconds() > self.ttl_seconds

    @property
    def is_actionable(self) -> bool:
        return self.is_approved and self.direction != SignalDirection.HOLD and not self.is_expired and self.status not in {"EXPIRED", "INVALIDATED"}



class SignalCombiner:
    """
    Ensemble aggregator and conflict resolver for strategy signals.
    """

    DEFAULT_WEIGHTS = {
        "trend_following": 0.25,
        "mean_reversion": 0.20,
        "breakout": 0.20,
        "vwap_reversion": 0.15,
        "mtf_confluence": 0.20,
    }

    def __init__(
        self,
        strategy_weights: dict[str, float] | None = None,
        min_composite_score: float = 0.65,
        min_consensus_ratio: float = 0.50,
        resolve_conflicts_to_hold: bool = True,
        min_voters: int = 1,
    ) -> None:
        self._weights = strategy_weights or self.DEFAULT_WEIGHTS
        self._min_composite_score = min_composite_score
        self._min_consensus = min_consensus_ratio
        self._resolve_conflicts_to_hold = resolve_conflicts_to_hold
        self._min_voters = max(1, min_voters)

    def combine(
        self,
        symbol: str,
        signals: list[StrategySignal],
        market_regime: str | None = None,
    ) -> CombinedSignal:
        """
        Combine a list of strategy signals into a single unified decision.
        """
        # Filter out inactive/None signals
        actionable_signals = [s for s in signals if s and s.is_actionable]

        if not actionable_signals:
            return CombinedSignal(
                symbol=symbol,
                direction=SignalDirection.HOLD,
                composite_score=0.0,
                confidence=0.0,
                consensus_ratio=0.0,
                contributing_strategies=[],
                reasons=["No actionable signals received from strategies (NO TRADE)."],
            )

        buy_signals = [s for s in actionable_signals if s.direction == SignalDirection.BUY]
        sell_signals = [s for s in actionable_signals if s.direction == SignalDirection.SELL]

        # ── 1. Conflict Resolution ───────────────────────────────────
        if buy_signals and sell_signals:
            # Both BUY and SELL signals exist
            if self._resolve_conflicts_to_hold:
                logger.warning(
                    "strategy_conflict_detected",
                    symbol=symbol,
                    num_buys=len(buy_signals),
                    num_sells=len(sell_signals),
                    action="holding_neutral",
                )
                return CombinedSignal(
                    symbol=symbol,
                    direction=SignalDirection.HOLD,
                    composite_score=0.0,
                    confidence=0.0,
                    consensus_ratio=0.0,
                    contributing_strategies=[s.strategy for s in actionable_signals],
                    reasons=[
                        f"Conflict detected: {len(buy_signals)} BUY vs {len(sell_signals)} SELL signals. "
                        f"Resolved to HOLD to protect capital."
                    ],
                    signals=actionable_signals,
                )

        # ── 2. Determine Consensus Direction ─────────────────────────
        dominant_signals = buy_signals if len(buy_signals) >= len(sell_signals) else sell_signals
        direction = dominant_signals[0].direction
        # Denominator counts every agent that voted (HOLD/abstain included), so a lone
        # directional vote among many neutral agents can no longer reach full consensus.
        total_voters = len([s for s in signals if s])
        consensus_ratio = len(dominant_signals) / max(len(actionable_signals), total_voters)

        # ── 3. Weighted Composite Scoring ────────────────────────────
        weighted_score_sum = 0.0
        weighted_conf_sum = 0.0
        total_weight = 0.0
        combined_reasons: list[str] = []

        stops: list[float] = []
        targets: list[float] = []
        exp_returns: list[float] = []
        risks: list[float] = []

        for sig in dominant_signals:
            w = self._weights.get(sig.strategy, 0.20)
            weighted_score_sum += sig.score * w
            weighted_conf_sum += sig.confidence * w
            total_weight += w

            combined_reasons.extend(sig.reasons)
            if sig.stop_suggestion:
                stops.append(sig.stop_suggestion)
            if sig.target_suggestion:
                targets.append(sig.target_suggestion)
            if sig.expected_return is not None:
                exp_returns.append(sig.expected_return)
            if sig.risk_estimate is not None:
                risks.append(sig.risk_estimate)

        norm_weight = max(1e-6, total_weight)
        composite_score = min(1.0, weighted_score_sum / norm_weight)
        confidence = min(1.0, weighted_conf_sum / norm_weight)

        # Multi-signal bonus: If multiple strategies agree, boost score slightly
        if len(dominant_signals) > 1:
            composite_score = min(1.0, composite_score * 1.05)
            confidence = min(1.0, confidence * 1.05)

        # ── 4. Conservative Target & Stop Selection ──────────────────
        # For BUY: highest stop-loss (closest to price, most defensive)
        # For SELL: lowest stop-loss (closest to price, most defensive)
        selected_stop = None
        selected_target = None

        if stops:
            selected_stop = max(stops) if direction == SignalDirection.BUY else min(stops)
        if targets:
            # Average expected targets
            selected_target = round(sum(targets) / len(targets), 2)

        mean_exp_return = round(sum(exp_returns) / len(exp_returns), 2) if exp_returns else None
        mean_risk = round(sum(risks) / len(risks), 2) if risks else None

        # ── 5. Approval Gate ─────────────────────────────────────────
        is_approved = (
            composite_score >= self._min_composite_score and
            consensus_ratio >= self._min_consensus and
            len(dominant_signals) >= self._min_voters
        )

        approval_note = (
            f"Approved (Score {composite_score:.2f} >= {self._min_composite_score:.2f})"
            if is_approved else
            f"Rejected (Score {composite_score:.2f} < {self._min_composite_score:.2f})"
        )
        combined_reasons.append(approval_note)

        return CombinedSignal(
            symbol=symbol,
            direction=direction if is_approved else SignalDirection.HOLD,
            composite_score=round(composite_score, 3),
            confidence=round(confidence, 3),
            consensus_ratio=round(consensus_ratio, 3),
            contributing_strategies=[s.strategy for s in dominant_signals],
            suggested_stop=selected_stop,
            suggested_target=selected_target,
            expected_return=mean_exp_return,
            risk_estimate=mean_risk,
            is_approved=is_approved,
            reasons=combined_reasons,
            signals=dominant_signals,
        )
